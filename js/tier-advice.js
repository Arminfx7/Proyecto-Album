window.getTierAdvice = (category, tier) => {
  const index = ['baja', 'media', 'alta'].indexOf(tier);
  const entries = category.products.filter(product => product.tier === tier);
  const text = window.tierAdvice[category.id]?.[index];
  if (!entries.length || !text) return null;
  const selected = category.id === 'celulares' && tier === 'media' ? 1 : 0;
  return { product: entries[selected], text };
};
